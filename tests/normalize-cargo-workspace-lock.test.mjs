import assert from "node:assert/strict";
import { normalizeWorkspaceLock } from "../scripts/normalize-cargo-workspace-lock.mjs";

const metadata = {
  workspace_members: ["path+file:///repo#codex-cli@0.163.0-alpha.10.2", "path+file:///repo#codex-core@0.163.0-alpha.10.2"],
  packages: [
    { id: "path+file:///repo#codex-cli@0.163.0-alpha.10.2", name: "codex-cli", version: "0.163.0-alpha.10.2", source: null },
    { id: "path+file:///repo#codex-core@0.163.0-alpha.10.2", name: "codex-core", version: "0.163.0-alpha.10.2", source: null },
  ],
};
const lock = `# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "codex-cli"\nversion = "0.0.0"\ndependencies = ["codex-core"]\n\n[[package]]\nname = "codex-core"\nversion = "0.0.0"\ndependencies = ["serde"]\n\n[[package]]\nname = "path-only-helper"\nversion = "1.2.3"\n\n[[package]]\nname = "serde"\nversion = "1.0.219"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "keep-this-checksum"\n\n[[package]]\nname = "git-helper"\nversion = "2.4.1"\nsource = "git+https://github.com/example/helper?rev=abc123#abc123def456"\n`;

const { text, report } = normalizeWorkspaceLock(metadata, lock);
assert.match(text, /name = "codex-cli"\nversion = "0\.163\.0-alpha\.10\.2"/);
assert.match(text, /name = "codex-core"\nversion = "0\.163\.0-alpha\.10\.2"/);
assert.match(text, /name = "path-only-helper"\nversion = "1\.2\.3"/);
assert.ok(text.includes('[[package]]\nname = "serde"\nversion = "1.0.219"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "keep-this-checksum"\n'));
assert.ok(text.endsWith('[[package]]\nname = "git-helper"\nversion = "2.4.1"\nsource = "git+https://github.com/example/helper?rev=abc123#abc123def456"\n'));
assert.equal(report.changed_packages.length, 2);
assert.match(report.normalized_lock_sha256, /^[a-f0-9]{64}$/);
assert.match(report.original_lock_sha256, /^[a-f0-9]{64}$/);
assert.match(report.lock_diff, /codex-cli/);
const secondPass = normalizeWorkspaceLock(metadata, text);
assert.equal(secondPass.text, text, "normalization is idempotent");
assert.equal(secondPass.report.changed_packages.length, 0);

assert.throws(() => normalizeWorkspaceLock(metadata, lock.replace('version = "0.0.0"', 'version = "9.9.9"')), /unexpected Cargo\.lock version/);
assert.throws(() => normalizeWorkspaceLock(metadata, lock.replace('name = "codex-core"\nversion = "0.0.0"', 'name = "codex-cli"\nversion = "0.0.0"')), /multiple source-less entries/);

console.log("PASS workspace Cargo.lock normalization preserves non-workspace and external package records");
