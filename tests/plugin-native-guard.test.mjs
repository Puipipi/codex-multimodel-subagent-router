import assert from 'node:assert/strict';
import {mkdtemp, mkdir, readFile, rm, writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {decideRoute} from '../scripts/route.mjs';
import {handleHook} from '../scripts/route-hook.mjs';
import {createApiProfile, createDefaultRouterSettings, effectiveRouterEnabled, saveRouterSettings} from '../scripts/native-api-settings.mjs';
import {createRouterSettingsService} from '../scripts/router-settings-mcp.mjs';

const root = await mkdtemp(path.join(os.tmpdir(), 'router-native-guard-'));
const priorHome = process.env.CODEX_HOME;
const priorLocal = process.env.LOCALAPPDATA;
const codexHome = path.join(root, 'codex');
process.env.CODEX_HOME = codexHome;
process.env.LOCALAPPDATA = path.join(root, 'local');
const guard = {state: 'disabled', reason: 'API patch has not passed compatibility checks', repairAttempted: false, updatedAt: '2026-10-27T00:00:00Z'};
const model = 'gpt-6.1-terra';
const models = [{value: model, title: 'GPT-6.1 Terra', reasoningEfforts: []}, {value: 'gpt-6-luna', title: 'Luna', reasoningEfforts: []}];
const settings = {...createDefaultRouterSettings(), mode: 'fixed', fixedExecutor: `native:${model}`};
const options = {routerSettings: settings, guardStatus: guard, readNativeModels: async () => models, currentModelResolver: async () => ({model}), stateDir: root, at: '2026-10-27T10:00:00+08:00'};
try {
  await mkdir(path.join(codexHome, 'router-runtime'), {recursive: true});
  await writeFile(path.join(codexHome, 'router-runtime', 'upgrade-status.json'), JSON.stringify(guard));
  await writeFile(path.join(codexHome, 'models_cache.json'), JSON.stringify({models: models.map(m => ({slug: m.value, display_name: m.title}))}));
  const actual = await decideRoute(options);
  assert.equal(actual.executor, 'native', 'API compatibility failure must not disable an exact native model');
  assert.equal(actual.native_spawn.model, model);
  assert.equal(actual.native_spawn.fork_turns, 'none');
  assert.equal((await decideRoute({...options, guardStatus: undefined, readGuardStatus: async () => {throw new Error('native routing must not read the API guard');}})).native_spawn.model, model);
  assert.equal(effectiveRouterEnabled(settings, guard, 'native'), true);
  assert.equal(effectiveRouterEnabled(settings, guard, 'api'), false);
  assert.equal(effectiveRouterEnabled({...settings, enabled: false}, guard, 'native'), false);
  assert.equal((await decideRoute({...options, routerSettings: {...settings, fixedExecutor: 'luna'}})).executor, 'luna');
  assert.equal((await decideRoute({...options, routerSettings: {...settings, fixedExecutor: 'same'}, mainModel: model})).native_spawn.model, model);
  await assert.rejects(decideRoute({...options, readNativeModels: async () => []}), /not present in the current Codex catalog/);
  const profile = createApiProfile({protocol: 'chat_completions', baseUrl: 'https://example.com/v1', model: 'test-model', reasoning: {supported: ['none'], default: 'none', parameter: 'none'}, credential: {type: 'env', name: 'TEST_ROUTER_KEY'}});
  const apiSettings = {...settings, fixedExecutor: profile.profileId, profiles: {[profile.profileId]: profile}};
  for (const executor of ['deepseek', profile.profileId]) {
    const blocked = await decideRoute({...options, routerSettings: apiSettings, executor});
    assert.equal(blocked.executor, 'off', 'API and DeepSeek remain guarded even as one-time overrides');
    assert.equal(blocked.source, 'guard_disabled');
    assert.equal(Object.hasOwn(blocked, 'native_spawn'), false);
  }
  const mixed = {...settings, mode: 'scheduled', schedule: {peak: `native:${model}`, valley: 'deepseek'}};
  assert.equal((await decideRoute({...options, routerSettings: mixed})).executor, 'native');
  assert.equal((await decideRoute({...options, routerSettings: mixed, at: '2026-10-27T22:00:00+08:00'})).source, 'guard_disabled');
  assert.equal((await decideRoute({...options, routerSettings: apiSettings, executor: `native:${model}`})).executor, 'native');
  const off = await decideRoute({...options, routerSettings: {...settings, enabled: false}, executor: `native:${model}`});
  assert.equal(off.source, 'disabled', 'the user off switch still takes precedence');
  const hook = await handleHook({input: {hook_event_name: 'UserPromptSubmit', session_id: 'native-guard-parent', model}, routerSettings: settings, guardStatus: guard, hookStateDir: path.join(root, 'hooks'), now: options.at});
  assert.equal(hook.route.executor, 'native');
  assert.ok(hook.output.hookSpecificOutput.additionalContext.includes(model));

  const settingsPath = path.join(root, 'router.json');
  const saved = await saveRouterSettings(settingsPath, settings, {expectedSha256: null});
  const env = {...process.env, CODEX_HOME: codexHome, LOCALAPPDATA: path.join(root, 'local')};
  const child = JSON.parse(execFileSync(process.execPath, [fileURLToPath(new URL('../scripts/native-agent.mjs', import.meta.url)), '--executor', `native:${model}`, '--settings', settingsPath, '--json'], {env, encoding: 'utf8', windowsHide: true}));
  assert.equal(child.model, model, 'the real native-agent CLI must also pass the native executor');
  let reads = 0;
  const service = createRouterSettingsService({settingsPath, env, guardStatus: async () => guard, readNativeModels: async () => models, collectDiagnostics: async () => {reads += 1; return {available: true, rootCause: 'uncertain', events: []};}});
  assert.equal((await service.callTool('router_connection_diagnostics', {}, {threadId: 'trusted-parent'})).payload.available, true);
  assert.equal(reads, 1, 'API compatibility failure does not block explicit local log diagnostics');
  await saveRouterSettings(settingsPath, {...settings, enabled: false}, {expectedSha256: saved.sha256});
  const stopped = (await service.callTool('router_connection_diagnostics', {}, {threadId: 'trusted-parent'})).payload;
  assert.equal(stopped.available, false);
  assert.equal(stopped.reason, 'routing_disabled', 'disabled diagnostics explain why no logs were read');
  assert.equal(reads, 1, 'the user off switch still prevents diagnostic reads');

  const html = await readFile(new URL('../ui/router-settings.html', import.meta.url), 'utf8');
  const renderSource = html.slice(html.indexOf('  function renderConfiguredExecutorStatus('), html.indexOf('  async function loadExecutorStatus('));
  const elements = new Map();
  const callbacks = new Map();
  const byId = id => {if (!elements.has(id)) elements.set(id, {dataset: {}, textContent: '', addEventListener: (event, callback) => callbacks.set(id, callback)}); return elements.get(id);};
  const context = {byId, setStatusLabel() {}, loadExecutorStatus() {throw new Error('native status must not load API status');}};
  vm.createContext(context);
  vm.runInContext(renderSource, context);
  context.snapshot = {settings, nativeModels: models, capabilities: {nativeModelsAvailable: true, guardStatus: guard}};
  vm.runInContext('renderConfiguredExecutorStatus(snapshot)', context);
  assert.equal(byId('install-status').dataset.state, 'on');
  assert.match(byId('install-state').textContent, /未调用/);
  assert.match(byId('executor-status-detail').textContent, /不受 API 兼容守卫影响/);
  context.snapshot = {...context.snapshot, settings: {...settings, fixedExecutor: 'deepseek'}};
  vm.runInContext('renderConfiguredExecutorStatus(snapshot)', context);
  assert.equal(byId('install-status').dataset.state, 'off');
  assert.match(byId('executor-status-detail').textContent, /原生模型仍可用/);
  context.snapshot = {...context.snapshot, settings: mixed};
  vm.runInContext('renderConfiguredExecutorStatus(snapshot)', context);
  assert.equal(byId('install-status').dataset.state, 'on', 'a mixed schedule preserves its native time windows');
  assert.match(byId('executor-status-detail').textContent, /DeepSeek.*停用/);
  context.snapshot = {...context.snapshot, settings: {...settings, enabled: false}};
  vm.runInContext('renderConfiguredExecutorStatus(snapshot)', context);
  assert.equal(byId('install-state').textContent, '分工已关闭');
  const diagnosticsSource = html.slice(html.indexOf('  byId("connection-diagnostics").addEventListener('), html.indexOf('  byId("reload-route").addEventListener('));
  context.messageOf = error => error.message;
  let diagnosticResult;
  context.callTool = async () => diagnosticResult;
  vm.runInContext(diagnosticsSource, context);
  diagnosticResult = {available: false, reason: 'routing_disabled'};
  await callbacks.get('connection-diagnostics')();
  assert.match(byId('connection-diagnostics-result').textContent, /开关已关闭.*未读取日志/);
  diagnosticResult = {available: false, reason: 'local_logs_unavailable'};
  await callbacks.get('connection-diagnostics')();
  assert.match(byId('connection-diagnostics-result').textContent, /不代表模型连接失败/);
  diagnosticResult = {available: true, events: []};
  await callbacks.get('connection-diagnostics')();
  assert.match(byId('connection-diagnostics-result').textContent, /不能据此确认连接成功/);
  diagnosticResult = {available: true, events: [{timestampUtc: '2026-10-27T00:00:00Z', errorClass: 'websocket_closed_before_completed'}]};
  await callbacks.get('connection-diagnostics')();
  assert.match(byId('connection-diagnostics-result').textContent, /未进行实时连接测试/);
  assert.match(byId('connection-diagnostics-result').textContent, /websocket_closed_before_completed/);
  assert.ok(html.includes('读取本地连接日志'));
  assert.ok(html.includes('不是实时连接测试'));
  console.log('Native/API guard isolation and diagnostic UI checks passed');
} finally {
  if (priorHome === undefined) delete process.env.CODEX_HOME; else process.env.CODEX_HOME = priorHome;
  if (priorLocal === undefined) delete process.env.LOCALAPPDATA; else process.env.LOCALAPPDATA = priorLocal;
  await rm(root, {recursive: true, force: true});
}
